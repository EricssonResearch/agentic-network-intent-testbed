#!/usr/bin/env python3
"""Appendix table of the reasoning-text keyword dictionary (one keyword list per category) -> tables/tab_taxonomy.tex"""
import json
from pathlib import Path
from common import REPO, DEFAULT_TABLES_DIR
tax = json.load(open(Path(__file__).with_name("reasoning_taxonomy.json")))
def esc(s): return s.replace('%', '\\%').replace('_', '\\_').replace('#', '\\#').replace('&', '\\&')
L = [r"% auto-generated by make_taxonomy_table.py from reasoning_taxonomy.json", r"\begin{table}[t]", r"\centering\footnotesize",
     r"\caption{Keyword dictionary of the reasoning-text classifier. Matching is case-insensitive substring matching on the comment after \texttt{\#}; a decision receives every category with at least one match (multi-label). A comment that starts with \texttt{error} is an API-error placeholder and is counted separately.}\label{tab:taxonomy}",
     r"\begin{adjustbox}{max width=\textwidth}", r"\begin{tabular}{lp{5.2cm}p{8.2cm}}", r"\toprule", r"Category & Description & Keywords \\", r"\midrule"]
for c, d in tax["categories"].items():
    kws = list(d.get("legacy", [])) + list(d.get("added", []))
    L.append(f"{esc(c.replace('_', ' '))} & {esc(d['description'])} & {esc(', '.join(kws))} \\\\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", r"\end{table}"]
(DEFAULT_TABLES_DIR / "tab_taxonomy.tex").write_text("\n".join(L) + "\n")
print("written", DEFAULT_TABLES_DIR / "tab_taxonomy.tex")
